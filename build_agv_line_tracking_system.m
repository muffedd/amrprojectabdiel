disp('=== Step 4: Calibrating Drive Wheels inside AGV_STEP_1_RIGID ===');
agv = [modelName, '/AGV_STEP_1_RIGID'];

% Disconnect signal lines from inports inside AGV_STEP_1_RIGID
lines = get_param(agv, 'Lines');
for l = 1:length(lines)
    sb = lines(l).SrcBlock;
    if ~isempty(sb) && all(sb ~= -1)
        name = get_param(sb(1), 'Name');
        if contains(name, 'Torque') || contains(name, 'Gain_') || contains(name, 'Inport_')
            delete_line(lines(l).Handle);
        end
    end
end

% Set Port 1 = Torque_Left, Port 2 = Torque_Right
if ~isempty(find_system(agv, 'SearchDepth', 1, 'Name', 'Torque_Right'))
    set_param([agv, '/Torque_Right'], 'Name', 'Inport_Right_Tmp');
end
if ~isempty(find_system(agv, 'SearchDepth', 1, 'Name', 'Torque_Left'))
    set_param([agv, '/Torque_Left'], 'Name', 'Inport_Left_Tmp');
end
