    dwa = sprintf('%s/Drive_Wheel_Assembly_STEP_%d_RIGID', agv, k);
    
    % Delete Const_Zero if present
    c_blk = [dwa, '/Const_Zero'];
    if ~isempty(find_system(dwa, 'SearchDepth', 1, 'Name', 'Const_Zero'))
        dlines = get_param(dwa, 'Lines');
        for l = 1:length(dlines)
            sb = dlines(l).SrcBlock;
            if ~isempty(sb) && all(sb ~= -1) && strcmp(get_param(sb(1), 'Name'), 'Const_Zero')
                delete_line(dlines(l).Handle);
            end
        end
        delete_block(c_blk);
    end
    
    % Locate or add Simulink-PS Converter and configure filtering
    ps_blk = [dwa, '/PS_Zero_Torque'];
    if isempty(find_system(dwa, 'SearchDepth', 1, 'Name', 'PS_Zero_Torque'))
        ps_blk = [dwa, '/PS_Torque'];
