% apply_corner_turn_upgrade.m
% Implements Early Corner Capture, 2-Phase Corner Turn, Yaw-Rate Derivative Damping,
% and Preserves 3-Station Pallet Stops.
clear; clc;
disp('=== Step 1: Loading Workspace and AGV_Warehouse_Sim Model ===');
evalin('base', 'run(''AGV_DataFile.m'')');

modelName = 'AGV_Warehouse_Sim';
if bdIsLoaded(modelName), close_system(modelName, 0); end
load_system(modelName);

disp('=== Step 2: Updating Line_Tracking_Controller Code ===');
mf_blk = [modelName, '/Line_Tracking_Controller'];
rt = sfroot;
m_chart = rt.find('Path', mf_blk, '-isa', 'Stateflow.EMChart');

controller_code = sprintf([...
'function [tau_L, tau_R, e_lat, e_heading, state_out, station_out] = Line_Tracking_Controller(pos, yaw, t)\n', ...
'%% AGV Line-Tracking, 3-Station Pallet-Stop State Machine & 2-Phase Corner Turn\n', ...
'%% pos: [X, Y] in meters (World frame)\n', ...
'%% yaw: chassis orientation in radians (World frame)\n', ...
'%% t: simulation time in seconds\n\n', ...
'X = pos(1);\n', ...
'Y = pos(2);\n\n', ...
'%% 3 Exact Stop Waypoints projected onto the black track loop:\n', ...
'%% Blue Station:  (0.0, -3.0)\n', ...
'%% Green Station: (5.0,  0.0)\n', ...
'%% Red Station:   (-2.5, 3.0)\n', ...
'stations = [  0.0, -3.0; ...  %% 1: Blue Station\n', ...
'              5.0,  0.0; ...  %% 2: Green Station\n', ...
'             -2.5,  3.0 ];    %% 3: Red Station\n\n', ...
'%% 4 Corner Vertices along the rectangular track loop:\n', ...
'%% Corner 1: ( 5.0, -3.0) - End of South segment (turn to East)\n', ...
'%% Corner 2: ( 5.0,  3.0) - End of East segment  (turn to North)\n', ...
'%% Corner 3: (-5.0,  3.0) - End of North segment (turn to West)\n', ...
'%% Corner 4: (-5.0, -3.0) - End of West segment  (turn to South)\n', ...
'corners = [  5.0, -3.0; ...\n', ...
'             5.0,  3.0; ...\n', ...
'            -5.0,  3.0; ...\n', ...
'            -5.0, -3.0 ];\n\n', ...
'%% Perpendicular Track Desired Headings:\n', ...
'%% Segment 1 (South): Eastward  -> theta_des =  0.0 rad (0 deg)\n', ...
'%% Segment 2 (East):  Northward -> theta_des =  pi/2 rad (+90 deg)\n', ...
'%% Segment 3 (North): Westward  -> theta_des =  pi rad   (180 deg)\n', ...
'%% Segment 4 (West):  Southward -> theta_des = -pi/2 rad (-90 deg)\n', ...
'yaw_des_table = [0.0, pi/2, pi, -pi/2];\n\n', ...
'%% State Machine Persistent Variables\n', ...
'%% state: 0: FOLLOW_LINE, 1: STOP_AT_PALLET, 2: COOLDOWN\n', ...
'persistent state target_station t_stop_start t_resume_start\n', ...
'persistent current_segment theta_prev X_prev Y_prev\n\n', ...
'if isempty(state)\n', ...
'    state = 0;\n', ...
'    target_station = 1;\n', ...
'    t_stop_start = 0.0;\n', ...
'    t_resume_start = 0.0;\n', ...
'    current_segment = 1;\n', ...
'    theta_prev = atan2(-sin(yaw), -cos(yaw));\n', ...
'    X_prev = X;\n', ...
'    Y_prev = Y;\n', ...
'end\n\n', ...
'%% Navigation Heading & Angular Velocity (wz)\n', ...
'dt = 0.01; %% Discrete sample time (100 Hz)\n', ...
'%% Navigation heading theta (0 rad = +X, pi/2 = +Y, pi = -X, -pi/2 = -Y)\n', ...
'%% At initial yaw = pi (180 deg), robot front faces +X (theta = 0)\n', ...
'theta = atan2(-sin(yaw), -cos(yaw));\n\n', ...
'%% Angular velocity wz (rad/s) with 2*pi phase unwrap protection:\n', ...
'dtheta = atan2(sin(theta - theta_prev), cos(theta - theta_prev));\n', ...
'wz = dtheta / dt;\n', ...
'theta_prev = theta;\n\n', ...
'%% Forward chassis velocity and wheel angular velocity for active damping:\n', ...
'vx = (X - X_prev) / dt;\n', ...
'vy = (Y - Y_prev) / dt;\n', ...
'v_fwd = vx * cos(theta) + vy * sin(theta);\n', ...
'X_prev = X;\n', ...
'Y_prev = Y;\n\n', ...
'R_wheel = 0.073182; %% Wheel outer radius (m)\n', ...
'wheel_vel = v_fwd / R_wheel; %% Wheel angular velocity (rad/s)\n\n', ...
'%% 3-Station Pallet-Stop State Machine\n', ...
'if state == 0 %% FOLLOW_LINE\n', ...
'    P_tgt = stations(target_station, :);\n', ...
'    dist_station = sqrt((X - P_tgt(1))^2 + (Y - P_tgt(2))^2);\n', ...
'    if dist_station < 0.25\n', ...
'        state = 1; %% STOP_AT_PALLET\n', ...
'        t_stop_start = t;\n', ...
'    end\n', ...
'elseif state == 1 %% STOP_AT_PALLET\n', ...
'    if (t - t_stop_start) >= 3.0\n', ...
'        state = 2; %% COOLDOWN\n', ...
'        t_resume_start = t;\n', ...
'        target_station = mod(target_station, 3) + 1;\n', ...
'    end\n', ...
'elseif state == 2 %% COOLDOWN\n', ...
'    if (t - t_resume_start) >= 3.0\n', ...
'        state = 0; %% Return to FOLLOW_LINE\n', ...
'    end\n', ...
'end\n\n', ...
'%% Early Corner Capture (switch to next corner waypoint when within 0.30 m)\n', ...
'if state ~= 1 %% Only evaluate corner transitions when moving\n', ...
'    C_curr = corners(current_segment, :);\n', ...
'    dist_corner = sqrt((X - C_curr(1))^2 + (Y - C_curr(2))^2);\n', ...
'    if dist_corner < 0.30\n', ...
'        current_segment = mod(current_segment, 4) + 1;\n', ...
'    end\n', ...
'end\n\n', ...
'%% Target Heading and Cross-Track Error for Current Segment\n', ...
'yaw_des = yaw_des_table(current_segment);\n', ...
'heading_err = atan2(sin(yaw_des - theta), cos(yaw_des - theta));\n\n', ...
'%% Cross-track error (positive when track is to the left of heading):\n', ...
'if current_segment == 1 %% South segment (Y = -3.0, facing +X)\n', ...
'    cross_track_err = -3.0 - Y;\n', ...
'elseif current_segment == 2 %% East segment (X = 5.0, facing +Y)\n', ...
'    cross_track_err = X - 5.0;\n', ...
'elseif current_segment == 3 %% North segment (Y = 3.0, facing -X)\n', ...
'    cross_track_err = Y - 3.0;\n', ...
'else %% West segment (X = -5.0, facing -Y)\n', ...
'    cross_track_err = -5.0 - X;\n', ...
'end\n\n', ...
'%% Steering Law with Yaw-Rate Derivative Damping\n', ...
'%% T_steer = Kp_yaw * heading_err + Kp_lat * cross_track_err - Kd_yaw * wz\n', ...
'%% Positive T_steer commands a LEFT turn (tau_R > tau_L).\n', ...
'%% Negative T_steer commands a RIGHT turn (tau_L > tau_R).\n', ...
'Kp_yaw = 1.2;\n', ...
'Kp_lat = 2.0;\n', ...
'Kd_yaw = 0.4;\n', ...
'T_steer = Kp_yaw * heading_err + Kp_lat * cross_track_err - Kd_yaw * wz;\n\n', ...
'%% 2-Phase Corner Turn & Propulsion Logic\n', ...
'T_nominal = 0.5; %% Cruise drive torque (N*m)\n\n', ...
'if state == 1 %% STOP_AT_PALLET (Preserve 3-second full-braking stop)\n', ...
'    T_drive = 0.0;\n', ...
'    T_steer = 0.0;\n', ...
'    tau_brake = -2.0 * wheel_vel; %% Active velocity damping\n', ...
'    tau_L = tau_brake;\n', ...
'    tau_R = tau_brake;\n', ...
'else\n', ...
'    %% CORNER_TURN mode: triggered whenever |heading_err| > 0.35 rad (~20 deg)\n', ...
'    if abs(heading_err) > 0.35\n', ...
'        %% Set forward drive torque to low forward creep (0.15 * T_nominal) so the AGV\n', ...
'        %% pivots cleanly in place onto the perpendicular track heading:\n', ...
'        T_drive = 0.15 * T_nominal;\n', ...
'    else\n', ...
'        %% Resume full straight-line cruise speed:\n', ...
'        T_drive = T_nominal;\n', ...
'    end\n', ...
'    \n', ...
'    tau_L = T_drive - T_steer;\n', ...
'    tau_R = T_drive + T_steer;\n', ...
'end\n\n', ...
'%% Torque Clamping to [-1.5, +1.5] N*m\n', ...
'tau_max = 1.5;\n', ...
'tau_L = max(-tau_max, min(tau_max, tau_L));\n', ...
'tau_R = max(-tau_max, min(tau_max, tau_R));\n\n', ...
'state_out = double(state);\n', ...
'station_out = double(target_station);\n', ...
'e_lat = cross_track_err;\n', ...
'e_heading = heading_err;\n']);

m_chart.Script = controller_code;
m_chart.ChartUpdate = 'DISCRETE';
m_chart.SampleTime = '0.01';
disp('  Line_Tracking_Controller successfully updated.');

disp('=== Step 3: Saving Model ===');
save_system(modelName);
disp(['  Saved ', modelName, '.slx']);

disp('=== Step 4: Synchronizing build_agv_line_tracking_system.m ===');
% Update build_agv_line_tracking_system.m with this exact controller script
% and settings so rebuilds permanently retain this logic
close_system(modelName, 0);
disp('  Model closed cleanly.');
