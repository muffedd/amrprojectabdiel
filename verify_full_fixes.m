% verify_full_fixes.m
clear; clc;
disp('=== Step 1: Loading Workspace and AGV_Warehouse_Sim Model ===');
evalin('base', 'run(''AGV_DataFile.m'')');

modelName = 'AGV_Warehouse_Sim';
if bdIsLoaded(modelName), close_system(modelName, 0); end
load_system(modelName);

disp('=== Step 2: Widening Warehouse Floor to 30 m x 30 m ===');
set_param([modelName, '/Warehouse_Floor'], 'BrickDimensions', '[30 30 0.1]');
disp('  Warehouse_Floor expanded to 30 m x 30 m x 0.1 m.');

disp('=== Step 3: Spawning Directly on Track with Yaw = 180 deg ===');
% Bottom straight segment is Y = -3.0 m, spanning X in [-5, 5].
% Blue station is at (0, -3.0). Spawn centered on line at X = -2.0 m, Y = -3.0 m.
% Front faces +X towards Blue station when Rz = 180 deg.
j6 = [modelName, '/Joint_6DOF'];
set_param(j6, 'PxPositionTargetSpecify', 'on', ...
              'PxPositionTargetValue', '-2.0', ...
              'PxPositionTargetPriority', 'High', ...
              'PyPositionTargetSpecify', 'on', ...
              'PyPositionTargetValue', '-3.0', ...
              'PyPositionTargetPriority', 'High', ...
              'SphPositionTargetSpecify', 'on', ...
              'SphPositionTargetPriority', 'High', ...
              'SphPositionTargetRotationMethod', 'StandardAxis', ...
              'SphPositionTargetRotationStandardAxis', '+Z', ...
              'SphPositionTargetRotationAngle', '180', ...
              'SphPositionTargetRotationAngleUnits', 'deg');
disp('  Joint_6DOF targets: Px = -2.0 m, Py = -3.0 m, Yaw = 180 deg.');

disp('=== Step 4: Updating Line_Tracking_Controller with Verified Signs ===');
mf_blk = [modelName, '/Line_Tracking_Controller'];
rt = sfroot;
m_chart = rt.find('Path', mf_blk, '-isa', 'Stateflow.EMChart');

controller_code = sprintf([...
'function [tau_L, tau_R, e_lat, e_heading, state_out, station_out] = Line_Tracking_Controller(pos, yaw, t)\n', ...
'%% AGV Line-Tracking, 3-Station Pallet-Stop State Machine & Differential Steering\n', ...
'X = pos(1);\n', ...
'Y = pos(2);\n\n', ...
'%% 3 Exact Stop Waypoints projected onto the black track line:\n', ...
'%% Blue Station 3:  Center (0, -3.8)  -> P_blue  = (0.0, -3.0)\n', ...
'%% Green Station 2: Center (5.8, 0)   -> P_green = (5.0,  0.0)\n', ...
'%% Red Station 1:   Center (-2.5, 3.8) -> P_red   = (-2.5, 3.0)\n', ...
'stations = [ 0.0, -3.0; ...\n', ...
'             5.0,  0.0; ...\n', ...
'            -2.5,  3.0];\n\n', ...
'%% State Machine Persistent Variables\n', ...
'%% State 0: FOLLOW_LINE\n', ...
'%% State 1: STOP_AT_PALLET (4 seconds stop)\n', ...
'%% State 2: RESUME_ROUTE (3 seconds cooldown / lock)\n', ...
'persistent state target_station t_stop_start t_resume_start visited\n', ...
'if isempty(state)\n', ...
'    state = 0;\n', ...
'    target_station = 1;\n', ...
'    t_stop_start = 0.0;\n', ...
'    t_resume_start = 0.0;\n', ...
'    visited = [false, false, false];\n', ...
'end\n\n', ...
'%% State Transitions\n', ...
'if state == 0 %% FOLLOW_LINE\n', ...
'    if target_station <= 3\n', ...
'        P_tgt = stations(target_station, :);\n', ...
'        dist = sqrt((X - P_tgt(1))^2 + (Y - P_tgt(2))^2);\n', ...
'        if dist < 0.15 && ~visited(target_station)\n', ...
'            state = 1; %% STOP_AT_PALLET\n', ...
'            t_stop_start = t;\n', ...
'            visited(target_station) = true;\n', ...
'        end\n', ...
'    end\n', ...
'elseif state == 1 %% STOP_AT_PALLET\n', ...
'    if (t - t_stop_start) >= 4.0\n', ...
'        state = 2; %% RESUME_ROUTE\n', ...
'        t_resume_start = t;\n', ...
'        target_station = target_station + 1;\n', ...
'    end\n', ...
'elseif state == 2 %% RESUME_ROUTE\n', ...
'    if (t - t_resume_start) >= 3.0\n', ...
'        state = 0; %% Return to FOLLOW_LINE\n', ...
'    end\n', ...
'end\n\n', ...
'%% Rectangular Track Loop: Perimeter = 32 m\n', ...
'%% South: s in [0, 10],   X = -5+s, Y = -3\n', ...
'%% East:  s in [10, 16],  X = 5,    Y = -3+(s-10)\n', ...
'%% North: s in [16, 26],  X = 5-(s-16), Y = 3\n', ...
'%% West:  s in [26, 32],  X = -5,   Y = 3-(s-26)\n', ...
's1 = max(0, min(10, X + 5));\n', ...
'd1_sq = (X - (-5 + s1))^2 + (Y - (-3))^2;\n', ...
's2 = 10 + max(0, min(6, Y + 3));\n', ...
'd2_sq = (X - 5)^2 + (Y - (-3 + (s2 - 10)))^2;\n', ...
's3 = 16 + max(0, min(10, 5 - X));\n', ...
'd3_sq = (X - (5 - (s3 - 16)))^2 + (Y - 3)^2;\n', ...
's4 = 26 + max(0, min(6, 3 - Y));\n', ...
'd4_sq = (X - (-5))^2 + (Y - (3 - (s4 - 26)))^2;\n\n', ...
'[~, min_idx] = min([d1_sq, d2_sq, d3_sq, d4_sq]);\n', ...
's_all = [s1, s2, s3, s4];\n', ...
's_curr = s_all(min_idx);\n\n', ...
'if min_idx == 1\n', ...
'    e_lat = Y - (-3.0); %% positive if left of track (inside loop)\n', ...
'elseif min_idx == 2\n', ...
'    e_lat = 5.0 - X;\n', ...
'elseif min_idx == 3\n', ...
'    e_lat = 3.0 - Y;\n', ...
'else\n', ...
'    e_lat = X - (-5.0);\n', ...
'end\n\n', ...
'%% Waypoint Lookahead Heading Control (L_look = 0.8 m)\n', ...
'L_look = 0.8;\n', ...
's_look = mod(s_curr + L_look, 32.0);\n', ...
'if s_look <= 10.0\n', ...
'    X_look = -5.0 + s_look;\n', ...
'    Y_look = -3.0;\n', ...
'elseif s_look <= 16.0\n', ...
'    X_look = 5.0;\n', ...
'    Y_look = -3.0 + (s_look - 10.0);\n', ...
'elseif s_look <= 26.0\n', ...
'    X_look = 5.0 - (s_look - 16.0);\n', ...
'    Y_look = 3.0;\n', ...
'else\n', ...
'    X_look = -5.0;\n', ...
'    Y_look = 3.0 - (s_look - 26.0);\n', ...
'end\n\n', ...
'psi_desired = atan2(Y_look - Y, X_look - X);\n', ...
'e_heading = atan2(sin(psi_desired - yaw), cos(psi_desired - yaw));\n\n', ...
'%% Steering Control (positive T_steer turns left, negative turns right)\n', ...
'Kp_heading = 8.0;\n', ...
'Kp_lat     = 4.0;\n', ...
'T_steer = Kp_heading * e_heading - Kp_lat * e_lat;\n\n', ...
'%% Longitudinal Propulsion\n', ...
'if state == 1 %% STOP_AT_PALLET\n', ...
'    T_drive = 0.0;\n', ...
'    T_steer = 0.0;\n', ...
'else\n', ...
'    %% Inverted drive torque to produce positive forward motion along +X\n', ...
'    T_drive = -4.0;\n', ...
'end\n\n', ...
'%% Differential drive torque distribution:\n', ...
'%% When T_steer > 0 (turn left), right wheels push more, left wheels push less\n', ...
'%% When T_steer < 0 (turn right), left wheels push more, right wheels push less\n', ...
'tau_L = T_drive - T_steer;\n', ...
'tau_R = T_drive + T_steer;\n\n', ...
'tau_max = 15.0;\n', ...
'tau_L = max(-tau_max, min(tau_max, tau_L));\n', ...
'tau_R = max(-tau_max, min(tau_max, tau_R));\n\n', ...
'state_out = double(state);\n', ...
'station_out = double(target_station);\n']);

m_chart.Script = controller_code;
m_chart.ChartUpdate = 'DISCRETE';
m_chart.SampleTime = '0.01';
disp('  Controller script updated with waypoint heading control and discrete sample time.');

% Add position logger if not present
if isempty(find_system(modelName, 'SearchDepth', 1, 'Name', 'Log_XY'))
    add_block('simulink/Sinks/To Workspace', [modelName, '/Log_XY'], 'VariableName', 'xy_log', 'SaveFormat', 'Timeseries');
    add_line(modelName, 'Get_XY/1', 'Log_XY/1', 'autorouting', 'on');
end

disp('=== Step 5: Saving Model ===');
save_system(modelName);
disp(['  Saved ', modelName, '.slx']);

disp('=== Step 6: Running 0.2-Second Test Simulation ===');
tic;
simOut = sim(modelName, 'StopTime', '0.2');
elapsed = toc;

xy_ts = simOut.xy_log;
t_vec = xy_ts.Time;
xy_data = xy_ts.Data;

if ndims(xy_data) == 3
    x0 = xy_data(1,1,1); y0 = xy_data(2,1,1);
    x_end = xy_data(1,1,end); y_end = xy_data(2,1,end);
else
    x0 = xy_data(1,1); y0 = xy_data(1,2);
    x_end = xy_data(end,1); y_end = xy_data(end,2);
end

fprintf('\n=== Simulation Results (0.2s Test) ===\n');
fprintf('Elapsed wall-clock time: %.2f seconds\n', elapsed);
fprintf('Start Pose: X = %.4f m, Y = %.4f m\n', x0, y0);
fprintf('End   Pose: X = %.4f m, Y = %.4f m\n', x_end, y_end);
fprintf('Displacement Delta X: %+.4f m\n', x_end - x0);
fprintf('Displacement Delta Y: %+.4f m\n', y_end - y0);

if (x_end - x0) > 0
    fprintf('\n--> CONFIRMED: AGV achieves POSITIVE FORWARD MOTION along the track (+X) toward Blue Station!\n');
else
    fprintf('\n--> Motion is not positive along +X.\n');
end

close_system(modelName, 0);
