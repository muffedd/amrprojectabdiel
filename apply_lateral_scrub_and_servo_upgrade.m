% apply_lateral_scrub_and_servo_upgrade.m
clear; clc;
disp('=== Step 1: Loading Workspace and AGV_Warehouse_Sim Model ===');
evalin('base', 'run(''AGV_DataFile.m'')');

modelName = 'AGV_Warehouse_Sim';
if bdIsLoaded(modelName), close_system(modelName, 0); end
load_system(modelName);

disp('=== Step 2: Lowering Wheel-Floor Contact Scrub Friction ===');
% Lower DynamicFriction to 0.25 and StaticFriction to 0.30 in all 4 contact force blocks
for k = 1:4
    scf = sprintf('%s/Spatial_Contact_Wheel_%d', modelName, k);
    set_param(scf, 'CoefficientOfDynamicFriction', '0.25', ...
                   'CoefficientOfStaticFriction', '0.30');
    disp(['  ', scf, ' updated: DynamicFriction = 0.25, StaticFriction = 0.30']);
end

disp('=== Step 3: Updating Line_Tracking_Controller with 4-State Machine & Speed Servo ===');
mf_blk = [modelName, '/Line_Tracking_Controller'];
rt = sfroot;
m_chart = rt.find('Path', mf_blk, '-isa', 'Stateflow.EMChart');

controller_code = sprintf([...
'function [tau_L, tau_R, e_lat, e_heading, state_out, station_out] = Line_Tracking_Controller(pos, yaw, t)\n', ...
'%% AGV Line-Tracking, 4-State Stop-and-Pivot Corner State Machine & Wheel Speed Servo\n', ...
'%% pos: [X, Y] in meters (World frame)\n', ...
'%% yaw: chassis orientation in radians (World frame)\n', ...
'%% t: simulation time in seconds\n\n', ...
'X = pos(1);\n', ...
'Y = pos(2);\n\n', ...
'%% 3 Exact Pallet Station Waypoints projected onto the black track loop:\n', ...
'%% Blue Station:  (0.0, -3.0)\n', ...
'%% Green Station: (5.0,  0.0)\n', ...
'%% Red Station:   (-2.5, 3.0)\n', ...
'stations = [  0.0, -3.0; ...  %% 1: Blue Station\n', ...
'              5.0,  0.0; ...  %% 2: Green Station\n', ...
'             -2.5,  3.0 ];    %% 3: Red Station\n\n', ...
'%% 4 Corner Vertices along the rectangular track loop:\n', ...
'%% Corner 1: ( 5.0, -3.0) - End of South edge (pivot to North)\n', ...
'%% Corner 2: ( 5.0,  3.0) - End of East edge  (pivot to West)\n', ...
'%% Corner 3: (-5.0,  3.0) - End of North edge (pivot to South)\n', ...
'%% Corner 4: (-5.0, -3.0) - End of West edge  (pivot to East)\n', ...
'corners = [  5.0, -3.0; ...\n', ...
'             5.0,  3.0; ...\n', ...
'            -5.0,  3.0; ...\n', ...
'            -5.0, -3.0 ];\n\n', ...
'%% Perpendicular Track Desired Headings:\n', ...
'%% Edge 1 (South): Eastward  -> theta_des =  0.0 rad (0 deg)\n', ...
'%% Edge 2 (East):  Northward -> theta_des =  pi/2 rad (+90 deg)\n', ...
'%% Edge 3 (North): Westward  -> theta_des =  pi rad   (180 deg)\n', ...
'%% Edge 4 (West):  Southward -> theta_des = -pi/2 rad (-90 deg)\n', ...
'yaw_des_table = [0.0, pi/2, pi, -pi/2];\n\n', ...
'%% State Machine States:\n', ...
'%% 0: FOLLOW_STRAIGHT\n', ...
'%% 1: STOP_AT_PALLET\n', ...
'%% 2: PIVOT_CORNER\n', ...
'%% 3: COOLDOWN_PALLET\n', ...
'persistent state target_station t_stop_start t_cooldown_start\n', ...
'persistent current_edge theta_prev X_prev Y_prev e_int_L e_int_R\n\n', ...
'if isempty(state)\n', ...
'    state = 0;\n', ...
'    target_station = 1;\n', ...
'    t_stop_start = 0.0;\n', ...
'    t_cooldown_start = 0.0;\n', ...
'    current_edge = 1;\n', ...
'    theta_prev = atan2(-sin(yaw), -cos(yaw));\n', ...
'    X_prev = X;\n', ...
'    Y_prev = Y;\n', ...
'    e_int_L = 0.0;\n', ...
'    e_int_R = 0.0;\n', ...
'end\n\n', ...
'%% Kinematic Calculations (Sample Time dt = 0.01 s)\n', ...
'dt = 0.01;\n', ...
'%% Navigation heading theta (where 0 rad = +X, pi/2 = +Y, pi = -X, -pi/2 = -Y)\n', ...
'theta = atan2(-sin(yaw), -cos(yaw));\n\n', ...
'%% Chassis Angular Velocity wz (rad/s) with phase-wrap protection:\n', ...
'dtheta = atan2(sin(theta - theta_prev), cos(theta - theta_prev));\n', ...
'wz = dtheta / dt;\n', ...
'theta_prev = theta;\n\n', ...
'%% Forward chassis velocity:\n', ...
'vx = (X - X_prev) / dt;\n', ...
'vy = (Y - Y_prev) / dt;\n', ...
'v_fwd_meas = vx * cos(theta) + vy * sin(theta);\n', ...
'X_prev = X;\n', ...
'Y_prev = Y;\n\n', ...
'R_wheel = 0.073182;  %% Wheel outer radius (m)\n', ...
'b_track = 0.629;     %% Half track width (m) [W = 1.258 m]\n\n', ...
'%% Actual wheel speeds from chassis kinematics (rad/s):\n', ...
'w_L_act = (v_fwd_meas - wz * b_track) / R_wheel;\n', ...
'w_R_act = (v_fwd_meas + wz * b_track) / R_wheel;\n\n', ...
'%% Target Heading and Cross-Track Lateral Error for Current Edge\n', ...
'yaw_des = yaw_des_table(current_edge);\n', ...
'e_yaw = atan2(sin(yaw_des - theta), cos(yaw_des - theta));\n\n', ...
'if current_edge == 1 %% South edge (Y = -3.0, moving +X)\n', ...
'    e_lat = -3.0 - Y;\n', ...
'elseif current_edge == 2 %% East edge (X = 5.0, moving +Y)\n', ...
'    e_lat = X - 5.0;\n', ...
'elseif current_edge == 3 %% North edge (Y = 3.0, moving -X)\n', ...
'    e_lat = Y - 3.0;\n', ...
'else %% West edge (X = -5.0, moving -Y)\n', ...
'    e_lat = -5.0 - X;\n', ...
'end\n\n', ...
'%% State Machine Transitions & Commanded Wheel Speeds (w_L_cmd, w_R_cmd)\n', ...
'w_base = 0.35 / R_wheel; %% Base wheel speed for v_fwd = 0.35 m/s (~4.78 rad/s)\n\n', ...
'%% Check Corner Proximity (within 0.15 m of next corner vertex)\n', ...
'C_next = corners(current_edge, :);\n', ...
'dist_corner = sqrt((X - C_next(1))^2 + (Y - C_next(2))^2);\n\n', ...
'%% Check Pallet Station Proximity (within 0.20 m of target bay)\n', ...
'P_tgt = stations(target_station, :);\n', ...
'dist_station = sqrt((X - P_tgt(1))^2 + (Y - P_tgt(2))^2);\n\n', ...
'if state == 0 %% FOLLOW_STRAIGHT\n', ...
'    if dist_station < 0.20\n', ...
'        state = 1; %% Enter STOP_AT_PALLET\n', ...
'        t_stop_start = t;\n', ...
'    elseif dist_corner < 0.15\n', ...
'        current_edge = mod(current_edge, 4) + 1; %% Advance to next track edge\n', ...
'        state = 2; %% Enter PIVOT_CORNER\n', ...
'    end\n', ...
'elseif state == 1 %% STOP_AT_PALLET\n', ...
'    if (t - t_stop_start) >= 3.0\n', ...
'        state = 3; %% Enter COOLDOWN_PALLET\n', ...
'        t_cooldown_start = t;\n', ...
'        target_station = mod(target_station, 3) + 1;\n', ...
'    end\n', ...
'elseif state == 2 %% PIVOT_CORNER\n', ...
'    %% Recalculate e_yaw for the new edge\n', ...
'    yaw_des_corner = yaw_des_table(current_edge);\n', ...
'    e_yaw_corner = atan2(sin(yaw_des_corner - theta), cos(yaw_des_corner - theta));\n', ...
'    if abs(e_yaw_corner) < 0.04 %% Reached within ~2.3 degrees of perpendicular heading\n', ...
'        state = 0; %% Switch back to FOLLOW_STRAIGHT\n', ...
'    end\n', ...
'elseif state == 3 %% COOLDOWN_PALLET\n', ...
'    if dist_corner < 0.15\n', ...
'        current_edge = mod(current_edge, 4) + 1;\n', ...
'        state = 2; %% Enter PIVOT_CORNER\n', ...
'    elseif (t - t_cooldown_start) >= 3.0\n', ...
'        state = 0; %% Cooldown finished, resume normal tracking\n', ...
'    end\n', ...
'end\n\n', ...
'%% Command Wheel Speeds Based on Active State\n', ...
'if state == 1 %% STOP_AT_PALLET\n', ...
'    w_L_cmd = 0.0;\n', ...
'    w_R_cmd = 0.0;\n', ...
'elseif state == 2 %% PIVOT_CORNER\n', ...
'    yaw_des_corner = yaw_des_table(current_edge);\n', ...
'    e_yaw_corner = atan2(sin(yaw_des_corner - theta), cos(yaw_des_corner - theta));\n', ...
'    e_heading = e_yaw_corner;\n', ...
'    s_yaw = sign(e_yaw_corner);\n', ...
'    if s_yaw == 0, s_yaw = 1.0; end\n', ...
'    %% Pure counter-rotating pivot speed (2.5 rad/s):\n', ...
'    w_L_cmd = -s_yaw * 2.5;\n', ...
'    w_R_cmd = +s_yaw * 2.5;\n', ...
'else %% FOLLOW_STRAIGHT (0) or COOLDOWN_PALLET (3)\n', ...
'    Kp_lat = 2.0;\n', ...
'    Kp_yaw = 1.5;\n', ...
'    Kd_yaw = 0.3;\n', ...
'    w_diff = Kp_lat * e_lat + Kp_yaw * e_yaw - Kd_yaw * wz;\n', ...
'    w_L_cmd = w_base - w_diff;\n', ...
'    w_R_cmd = w_base + w_diff;\n', ...
'end\n\n', ...
'%% High-Gain Inner Wheel-Velocity PI Speed Servo\n', ...
'err_L = w_L_cmd - w_L_act;\n', ...
'err_R = w_R_cmd - w_R_act;\n\n', ...
'Kp_servo = 3.0;\n', ...
'Ki_servo = 0.5;\n\n', ...
'e_int_L = e_int_L + err_L * dt;\n', ...
'e_int_R = e_int_R + err_R * dt;\n\n', ...
'%% Anti-windup clamping on integral terms:\n', ...
'e_int_L = max(-4.0, min(4.0, e_int_L));\n', ...
'e_int_R = max(-4.0, min(4.0, e_int_R));\n\n', ...
'tau_L_raw = Kp_servo * err_L + Ki_servo * e_int_L;\n', ...
'tau_R_raw = Kp_servo * err_R + Ki_servo * e_int_R;\n\n', ...
'%% Higher Steering Torque Clamp ([-8.0, +8.0] N*m)\n', ...
'tau_limit = 8.0;\n', ...
'tau_L = max(-tau_limit, min(tau_limit, tau_L_raw));\n', ...
'tau_R = max(-tau_limit, min(tau_limit, tau_R_raw));\n\n', ...
'state_out = double(state);\n', ...
'station_out = double(target_station);\n', ...
'e_heading = e_yaw;\n']);

m_chart.Script = controller_code;
m_chart.ChartUpdate = 'DISCRETE';
m_chart.SampleTime = '0.01';
disp('  Line_Tracking_Controller chart updated with 4-state machine and high-gain PI speed servo.');

disp('=== Step 4: Saving Model ===');
save_system(modelName);
disp(['  Saved ', modelName, '.slx']);

disp('=== Step 5: Running 0.2-Second Compile Check Simulation ===');
tic;
simOut = sim(modelName, 'StopTime', '0.2');
elapsed = toc;

xy_ts = simOut.xy_log;
xy_data = xy_ts.Data;
yaw_data = simOut.yaw_log.Data;

if ndims(xy_data) == 3
    x0 = xy_data(1,1,1); y0 = xy_data(2,1,1);
    x_end = xy_data(1,1,end); y_end = xy_data(2,1,end);
else
    x0 = xy_data(1,1); y0 = xy_data(1,2);
    x_end = xy_data(end,1); y_end = xy_data(end,2);
end
psi0 = yaw_data(1); psi_end = yaw_data(end);

fprintf('\n================== 0.2s COMPILE & SIMULATION CHECK ==================\n');
fprintf('Simulation Time Elapsed: %.2f seconds\n', elapsed);
fprintf('Start Pose: X = %+.4f m, Y = %+.4f m, Yaw = %+.4f rad (%.2f deg)\n', ...
    x0, y0, psi0, psi0*180/pi);
fprintf('End Pose:   X = %+.4f m, Y = %+.4f m, Yaw = %+.4f rad (%.2f deg)\n', ...
    x_end, y_end, psi_end, psi_end*180/pi);
fprintf('Displacement Delta X: %+.5f m\n', x_end - x0);
fprintf('Displacement Delta Y: %+.5f m\n', y_end - y0);
fprintf('Displacement Delta Yaw: %+.5f rad\n', psi_end - psi0);

assert((x_end - x0) > 0, 'AGV did not move forward along +X');
assert(abs(y_end - y0) < 0.05, 'AGV drifted excessively in lateral direction');
fprintf('\n>>> SUCCESS: MODEL COMPILED AND SIMULATED WITH ZERO ERRORS! <<<\n');

close_system(modelName, 0);
